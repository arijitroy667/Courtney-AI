import asyncio
import os
from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import PydanticOutputParser
from pydantic import BaseModel,Field

load_dotenv()  # Load variables from .env

model = ChatGoogleGenerativeAI(model="gemini-2.5-flash")

class Response_format(BaseModel):
    content: str = Field(description="The content generated by the model")
    confidence_score: int = Field(gt=0,lt=11,description="Provide a confidence score for the content generated")
    Reason: str = Field(description="The reason for the content generated by the model")

parser = PydanticOutputParser(pydantic_object=Response_format)



async def run_gpt(prompt: str):
    await asyncio.sleep(1)
    template = PromptTemplate(
        template=prompt,
        input_variables=[],
        partial_variables={'format_instruction': parser.get_format_instructions()}
    )
    chain = template | model | parser
    
    return chain.invoke({})