import asyncio
import os
import json
import re
from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import PydanticOutputParser
from pydantic import BaseModel, Field

load_dotenv()

model = ChatGoogleGenerativeAI(model="gemini-2.0-flash")

class Response_format(BaseModel):
    content: str = Field(description="The content generated by the model")
    confidence_score: int = Field(ge=1, le=10, description="Provide a confidence score for the content generated (1-10)")
    Reason: str = Field(description="The reason for the content generated by the model")

parser = PydanticOutputParser(pydantic_object=Response_format)

def extract_json_from_markdown(text: str) -> str:
    """Extract JSON from markdown code blocks"""
    text = text.strip()
    
    # Remove ```json and ``` markers
    if text.startswith("```json"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    
    if text.endswith("```"):
        text = text[:-3]
    
    return text.strip()

async def run_grok(prompt: str):
    await asyncio.sleep(1)

    template = PromptTemplate(
        template="""You MUST respond with ONLY valid JSON. Do not wrap your response in markdown code blocks or backticks.

{prompt}

{format_instructions}

Remember: Output ONLY the JSON object, nothing else.""",
        input_variables=["prompt"],
        partial_variables={'format_instructions': parser.get_format_instructions()}
    )
    
    try:
        chain = template | model
        response = chain.invoke({"prompt": prompt})
        
        # Get the raw text content
        raw_text = response.content if hasattr(response, 'content') else str(response)
        # Ensure raw_text is a string
        if not isinstance(raw_text, str):
            raw_text = str(raw_text)
        
        # Clean markdown formatting
        cleaned_text = extract_json_from_markdown(raw_text)
        
        # Try to parse with the Pydantic parser
        try:
            # Parse the cleaned JSON string into the Pydantic model
            result = parser.parse(cleaned_text)
            return result
        except Exception as parse_error:
            print(f"Pydantic parsing failed: {parse_error}")
            print(f"Attempting manual JSON parse...")
            
            # Fallback: manual JSON parsing
            json_obj = json.loads(cleaned_text)
            return Response_format(**json_obj)
            
    except Exception as e:
        print(f"Error in Gemini agent: {e}")
        print(f"Raw response (first 500 chars): {raw_text[:500] if 'raw_text' in locals() else 'N/A'}")
        
        # Return a fallback response
        return Response_format(
            content=f"Error processing Gemini response: {str(e)}",
            confidence_score=5,
            Reason="An error occurred during processing"
        )